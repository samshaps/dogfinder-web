const BREED_BY_SLUG = new Map(BREEDS.map((b) => [b.slug, b]));

export function getBreedBySlug(slug: string): BreedEntry | undefined {
  return BREED_BY_SLUG.get(slug);
}

export function getPopularBreeds(): BreedEntry[] {
  return BREEDS.filter((b) => b.popular);
}

/** All substrings that identify this breed, lowercased. */
export function breedMatchTerms(breed: BreedEntry): string[] {
  return [breed.keyword, ...(breed.aliases ?? [])].map((t) => t.toLowerCase());
}

/** True when any of a dog's breed labels contains one of this breed's match terms. */
export function dogMatchesBreed(dogBreeds: string[], breed: BreedEntry): boolean {
  const terms = breedMatchTerms(breed);
  const excluded = (breed.exclude ?? []).map((t) => t.toLowerCase());
  return dogBreeds.some((label) => {
    const lower = label.toLowerCase();
    if (excluded.some((t) => lower.includes(t))) return false;
    return terms.some((t) => lower.includes(t));
  });
}

